#!/bin/bash
# input:  one target name: geo | figshare | arrayexpress
# output: raw public files under /LARGE1/gr10634/gaozy/aml_niche_net/00_raw/public/{GEO,figshare,scilifelab}/...,
#         each directory with download.log, md5sums.txt and PROVENANCE.txt
# what it does: downloads the public AML datasets approved by the user on 2026-11-13 (per-cell genotype truth sets
#         and an AML + normal-marrow cohort), resumable (wget -c), and records source URL, date, size and md5.
# Runs on the login node (compute nodes have no network). Series matrices are kept INSIDE the raw directory
# (series_matrix/) so that 00_curated_manifest.R, which expects meta_*.csv in every 00_raw/metadata/<GSE>/ dir,
# is not broken before a meta table exists.
# Known run notes (2026-11-13): the arrayexpress target left P15R_raw_feature_bc_matrix.h5 at 0 bytes (flagged by the
# size check) and it was re-fetched by hand; the GEO series-matrix fetch returned nothing and is not needed downstream.
# Do not edit this file while a target is running: bash reads the script as it goes.
set -uo pipefail
RAW=/LARGE1/gr10634/gaozy/aml_niche_net/00_raw/public
STAMP=$(date -Iseconds)
WHO=$(whoami)
NOTE="downloaded by $WHO; approved by the user 2026-11-13 (per-cell genotype truth sets; AML + NBM cohort)"

provenance() {  # dir, study description
  local d=$1; local desc=$2
  ( cd "$d" && md5sum $(find . -maxdepth 2 -type f ! -name '*.txt' ! -name '*.log' ! -name '*.json' | sort) > md5sums.txt )
  {
    echo "study: $desc"
    echo "downloaded: $STAMP ($NOTE)"
    echo "files (size_bytes  md5  name):"
    while read -r m f; do printf '  %s  %s  %s\n' "$(stat -c %s "$d/$f")" "$m" "$f"; done < "$d/md5sums.txt"
  } > "$d/PROVENANCE.txt"
  echo "[done] $d"
}

geo() {
  # 1. GSE230559 Sirenko 2025 Cell Stem Cell (Papaemmanuil/Landau): IDH-mutant AML, GoT per-cell genotyping
  local d=$RAW/GEO/GSE230559_RAW; mkdir -p "$d/series_matrix"
  local base=https://ftp.ncbi.nlm.nih.gov/geo/series/GSE230nnn/GSE230559
  for f in filelist.txt GSE230559_CITEseq_panels.xlsx GSE230559_RAW.tar \
           GSE230559_IDH_AML_integrated_seurat_obejct.rds.gz GSE230559_sirenko_CSC_2025_final_object.rds; do
    wget -c -q -O "$d/$f" "$base/suppl/$f" || echo "[fail] $f"
  done
  ( cd "$d/series_matrix" && wget -c -q -r -np -nd -l1 -A 'GSE230559*series_matrix.txt.gz' "$base/matrix/" )
  provenance "$d" "GSE230559 Sirenko M ... Papaemmanuil E, Cell Stem Cell 2025 (PMID 40409258); IDH-mutant AML Dx/CR/Rel, clonal haematopoiesis carriers, donors; 10x 5' GEX + GoT genotyping + CITE-seq; source $base/suppl/"
  # 2. GSE146173 AMLCG bulk RNA-seq (246 patients, genotype + OS): L2 survival anchor (bulk, not single cell)
  d=$RAW/GEO/GSE146173_RAW; mkdir -p "$d/series_matrix"
  base=https://ftp.ncbi.nlm.nih.gov/geo/series/GSE146nnn/GSE146173
  for f in GSE146173_GEO_exon_counts.txt.gz GSE146173_GEO_intron_counts.txt.gz GSE146173_GEO_known_SJ_counts.txt.gz \
           GSE146173_GEO_novel_SJ_counts.txt.gz GSE146173_GEO_raw_gene_counts.txt.gz GSE146173_GEO_raw_isoform_counts.txt.gz; do
    wget -c -q -O "$d/$f" "$base/suppl/$f" || echo "[fail] $f"
  done
  ( cd "$d/series_matrix" && wget -c -q -r -np -nd -l1 -A 'GSE146173*series_matrix.txt.gz' "$base/matrix/" )
  provenance "$d" "GSE146173 AMLCG 1999/2008 bulk RNA-seq, 246 AML with per-sample genotype and overall survival (Herold et al.); source $base/suppl/"
}

figshare_article() {  # article_id, dest dir, description
  local id=$1; local d=$2; local desc=$3; mkdir -p "$d"
  curl -s "https://api.figshare.com/v2/articles/$id" > "$d/figshare_article_$id.json"
  python3 -I - "$d/figshare_article_$id.json" "$d" <<'PY'
import json, sys, subprocess, hashlib, os
meta = json.load(open(sys.argv[1])); dest = sys.argv[2]
bad = []
for f in meta["files"]:
    out = os.path.join(dest, f["name"])
    subprocess.run(["wget", "-c", "-q", "-O", out, f["download_url"]])
    h = hashlib.md5()
    with open(out, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 24), b""): h.update(chunk)
    ok = (not f.get("computed_md5")) or h.hexdigest() == f["computed_md5"]
    print(("[ok]  " if ok else "[MD5 MISMATCH] "), f["name"], os.path.getsize(out), h.hexdigest(), f.get("computed_md5", ""))
    if not ok: bad.append(f["name"])
print("md5 mismatches:", bad)
PY
  provenance "$d" "$desc"
}

figshare() {
  figshare_article 20291628 "$RAW/figshare/CloneTracer_20291628" \
    "CloneTracer main cohort Seurat object (Beneyto-Calabuig ... Velten, Cell Stem Cell 2023, doi 10.1016/j.stem.2023.04.001); 19 AML patients, per-cell leukaemia probability + healthy/leukemic/unsure; figshare 10.6084/m9.figshare.20291628, CC BY 4.0"
  figshare_article 23715648 "$RAW/scilifelab/Lilljebjorn2025_23715648" \
    "Lilljebjorn ... Fioretos, Nat Commun 2025 (PMID 41290664): 10x 3' v3 scRNA of 38 AML + NBM MNC/CD34 samples, per-sample Cell Ranger h5 + Seurat object; SciLifeLab Data Repository 10.17044/scilifelab.23715648, CC BY-NC-ND 4.0"
}

arrayexpress() {
  # 3. E-MTAB-16321 Ung et al. 2026 iScience: CITE-seq, 26 AML diagnosis + 26 matched relapse + 10 healthy donors
  #    (4 frozen STEMCELL 70001 + 6 fresh CGT Global), 10x 5' v2; raw (unfiltered) Cell Ranger h5 per library
  local d=$RAW/ArrayExpress/E-MTAB-16321; mkdir -p "$d"
  curl -s "https://www.ebi.ac.uk/biostudies/api/v1/studies/E-MTAB-16321" > "$d/biostudies_E-MTAB-16321.json"
  python3 -I - "$d/biostudies_E-MTAB-16321.json" "$d" <<'PY'
import json, sys, subprocess, os
s = json.load(open(sys.argv[1])); dest = sys.argv[2]
files = []
def walk(x):
    if isinstance(x, dict):
        for f in x.get("files", []):
            for g in (f if isinstance(f, list) else [f]):
                if isinstance(g, dict) and "path" in g: files.append((g["path"], g.get("size")))
        for v in x.values(): walk(v)
    elif isinstance(x, list):
        for v in x: walk(v)
walk(s)
base = "https://ftp.ebi.ac.uk/biostudies/fire/E-MTAB-/321/E-MTAB-16321/Files/"
bad = []
for path, size in files:
    out = os.path.join(dest, os.path.basename(path))
    subprocess.run(["wget", "-c", "-q", "-O", out, base + path])
    got = os.path.getsize(out) if os.path.exists(out) else -1
    ok = (size is None) or got == size
    print(("[ok]  " if ok else "[SIZE MISMATCH] "), path, got, size)
    if not ok: bad.append(path)
print("n files", len(files), "size mismatches:", bad)
PY
  provenance "$d" "E-MTAB-16321 Ung ... iScience 2026 (PMID 41959675): CITE-seq of 52 matched AML diagnosis/relapse samples (26 patients) + 10 healthy donors, 10x 5' v2; raw_feature_bc_matrix.h5 per library; source https://ftp.ebi.ac.uk/biostudies/fire/E-MTAB-/321/E-MTAB-16321/Files/"
}

case "${1:-}" in
  geo) geo ;;
  figshare) figshare ;;
  arrayexpress) arrayexpress ;;
  *) echo "usage: $0 geo|figshare|arrayexpress"; exit 1 ;;
esac
