#!/bin/bash
# input:  one target name: zenodo | geo
#         geo reads its file list from download_2026-11-14_loy_cohorts_geo_files.tsv (columns: GSE  dest_subdir  url)
#         next to this script, so the list can be written after the zenodo target has started (bash streams this file).
# output: zenodo -> /LARGE1/gr10634/gaozy/aml_niche_net/00_raw/public/Zenodo/zenodo.18528442/ (all 23 record files,
#                   md5.txt verified against the Zenodo API checksums in record.json, PROVENANCE.txt appended)
#         geo    -> /LARGE1/gr10634/gaozy/aml_niche_net/00_raw/public/GEO/<GSE>_RAW/ with md5sums.txt + PROVENANCE.txt
# what it does: downloads the cohorts approved by the user on 2026-11-14 for the LOY (chrY loss) case search:
#         the Zeng 2025 Blood Cancer Discovery 21-cohort pack (Zenodo 18528442, ~33 GB, raw UMI counts kept) and
#         the GEO series listed in the TSV. Resumable (wget -c), 4 files in parallel, md5-checked.
# Usage (login node only; compute nodes have no network):
#   nohup bash scripts/00_ingest/download/download_2026-11-14_loy_cohorts.sh zenodo > 00_project/logs/dl_zenodo_2026-11-14.log 2>&1 &
#   nohup bash scripts/00_ingest/download/download_2026-11-14_loy_cohorts.sh geo    > 00_project/logs/dl_geo_2026-11-14.log 2>&1 &
# WHY: the on-disk 16 datasets hold 3 clonal -Y AML and 0 subclonal cases (report reports/2026-11_loy/REPORT_step0-1_2026-11-14.md);
#      the within-patient -Y vs Y+ design (H2) needs more male AML, and these packs keep integer counts and chrY genes.
# Known run note (2026-11-14 18:20): the first run used xargs -n 2 and silently dropped every second file; killed at 18:27,
#   fixed to -n 1 (+ size-based skip of complete files) and restarted; partial files were resumed by wget -c.
# Do not edit this file while a target is running.
set -uo pipefail
RAW=/LARGE1/gr10634/gaozy/aml_niche_net/00_raw/public
HERE=$(cd "$(dirname "$0")" && pwd)
STAMP=$(date -Iseconds)
WHO=$(whoami)
NOTE="downloaded by $WHO; approved by the user 2026-11-14 (LOY case search: Zeng 2025 21-cohort pack + complex-karyotype/TP53 GEO cohorts)"

fetch_one() {  # url, out, [expected_size]  (wget -c resumes partial files; -q keeps the log readable)
  local url=$1; local out=$2; local want=${3:-}
  [ -n "$want" ] || want=$(curl -sI "$url" | tr -d '\r' | awk 'tolower($1)=="content-length:"{print $2}' | tail -1)
  if [ -n "$want" ] && [ -f "$out" ] && [ "$(stat -c %s "$out")" = "$want" ]; then
    echo "[skip] $want B  already complete  $(basename "$out")"; return 0
  fi
  local t0=$(date +%s)
  if wget -c -q -O "$out" "$url"; then
    echo "[ok]   $(stat -c %s "$out") B  $(( $(date +%s) - t0 )) s  $(basename "$out")"
  else
    echo "[fail] $(basename "$out")  $url"
  fi
}
export -f fetch_one

zenodo() {
  local d=$RAW/Zenodo/zenodo.18528442; mkdir -p "$d"
  local rec=$d/record.json
  [ -s "$rec" ] || curl -s "https://zenodo.org/api/records/18528442" > "$rec"
  # url<TAB>filename<TAB>md5 from the API record; Montefiori + xlsx are already on disk and verified (wget -c skips them)
  python3 -I - "$rec" <<'PY' > "$d/filelist.tsv"
import json, sys
r = json.load(open(sys.argv[1]))
for f in sorted(r["files"], key=lambda x: x["size"]):
    print(f["links"]["self"], f["key"], f["checksum"].replace("md5:", ""), f["size"], sep="\t")
PY
  echo "[start] $STAMP  $(wc -l < "$d/filelist.tsv") files"
  # one line per file (url<TAB>out<TAB>size); xargs -n 1 hands exactly one line to each worker as $0
  cut -f1,2,4 "$d/filelist.tsv" | while IFS=$'\t' read -r url key size; do printf '%s\t%s\t%s\n' "$url" "$d/$key" "$size"; done \
    | xargs -P 4 -n 1 -d '\n' bash -c 'IFS=$'"'"'\t'"'"' read -r u o z <<< "$0"; fetch_one "$u" "$o" "$z"' 2>&1
  # md5 verification against the API checksums
  : > "$d/md5.txt"; local bad=0
  while IFS=$'\t' read -r url key md5 size; do
    local have; have=$(md5sum "$d/$key" | cut -d' ' -f1)
    if [ "$have" = "$md5" ] && [ "$(stat -c %s "$d/$key")" = "$size" ]; then
      echo "$have  $key" >> "$d/md5.txt"; echo "[md5 ok]  $key"
    else
      echo "[MD5 MISMATCH]  $key  have=$have want=$md5  size=$(stat -c %s "$d/$key")/$size"; bad=$((bad+1))
    fi
  done < "$d/filelist.tsv"
  {
    echo ""
    echo "Fetched (full pack): $(date -Iseconds) by $WHO, user-approved 2026-11-14 (LOY case search, all 23 record files)."
    echo "Verified: $(grep -c . "$d/md5.txt") of $(wc -l < "$d/filelist.tsv") files match the API md5 + size; mismatches: $bad."
  } >> "$d/PROVENANCE.txt"
  echo "[done] zenodo  mismatches=$bad  $(date -Iseconds)"
}

geo() {
  local list=$HERE/download_2026-11-14_loy_cohorts_geo_files.tsv
  [ -s "$list" ] || { echo "[fail] missing $list"; exit 1; }
  grep -v '^#' "$list" | while IFS=$'\t' read -r gse sub url; do
    local d=$RAW/GEO/${gse}_RAW/$sub; mkdir -p "$d"
    printf '%s\t%s/%s\n' "$url" "$d" "$(basename "$url")"
  done | xargs -P 4 -n 1 -d '\n' bash -c 'IFS=$'"'"'\t'"'"' read -r u o <<< "$0"; fetch_one "$u" "$o"' 2>&1
  for gse in $(grep -v '^#' "$list" | cut -f1 | sort -u); do
    local d=$RAW/GEO/${gse}_RAW
    ( cd "$d" && md5sum $(find . -type f ! -name '*.txt' ! -name '*.log' ! -name 'PROVENANCE*' | sort) > md5sums.txt )
    {
      echo "study: $gse (see $HERE/download_2026-11-14_loy_cohorts_geo_files.tsv for the source URLs)"
      echo "downloaded: $STAMP ($NOTE)"
      echo "files (size_bytes  md5  name):"
      while read -r m f; do printf '  %s  %s  %s\n' "$(stat -c %s "$d/$f")" "$m" "$f"; done < "$d/md5sums.txt"
    } > "$d/PROVENANCE.txt"
    echo "[done] $d"
  done
}

case "${1:-}" in
  zenodo) zenodo ;;
  geo) geo ;;
  *) echo "usage: $0 zenodo|geo"; exit 1 ;;
esac
